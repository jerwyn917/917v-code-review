#!/usr/bin/env python3
"""Render the quick-scan report (writes only to --out).

The quick scan runs the deterministic scripts only: no reviewer agents, no
validation, no findings. Everything in it is a LEAD that a full review must
confirm against the source before it becomes a finding.

Inputs:
  --stack   stack.json         output of detect-stack.py
  --signals signals.json       output of scan-signals.py
  --imports import-graph.json  optional, output of import-graph.py
  --scope   scope.json         optional, output of diff-scope.py (diff scans)
Output: <out>/scan.md, plus a JSON summary on stdout.

Usage: render-scan.py --root <repo> --stack S --signals G [--imports I] [--scope C] -o docs/code-review
"""

import argparse
import datetime
import importlib.util
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import OUTPUT_DIR, check_output_path, claim_output_dir, dump_json, load_json  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "render_reports", os.path.join(os.path.dirname(os.path.abspath(__file__)), "render-reports.py"))
render_reports = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(render_reports)
cell = render_reports.cell

AREA = {"security-reviewer": "Security", "devops-reviewer": "DevOps & Infrastructure",
        "database-reviewer": "Database", "architecture-reviewer": "Architecture & Code Quality",
        "performance-reviewer": "Performance", "backend-reviewer": "API & Backend",
        "frontend-reviewer": "Frontend", "testing-reviewer": "Testing"}
ORDER = list(AREA)
MAX_LEADS_PER_AREA = 15


def area(agent):
    return AREA.get(agent, agent)


def code_span(text):
    """Markdown inline code that keeps backticks in the snippet verbatim."""
    if not text:
        return ""
    if "`" not in text:
        return "`%s`" % text
    return "`` %s ``" % text


def render(root, stack, signals, imports=None, scope=None, out_dir=None):
    sigs = signals.get("signals") or []
    by_agent = {}
    for s in sigs:
        by_agent.setdefault(s.get("agent"), []).append(s)
    agents = sorted(by_agent, key=lambda a: (ORDER.index(a) if a in ORDER else 99, a))
    cycles = (imports or {}).get("cycles") or []
    repo = os.path.basename(os.path.abspath(root))
    scope_desc = scope["description"] if scope else "entire repository"
    files_scanned = signals.get("files_scanned", 0)

    lines = ["# Quick scan — %s" % repo, "",
             "| | |", "|---|---|",
             "| **Repository** | %s |" % cell(repo),
             "| **Scope** | %s |" % cell(scope_desc + (" — %d files, %d changed lines" % (
                 scope["files_changed"], scope["lines_changed"]) if scope else "")),
             "| **Date** | %s |" % datetime.date.today().isoformat(),
             "| **Commit** | %s |" % cell(render_reports.commit_info(root)),
             "| **Generated by** | 917v-code-review v%s, quick scan (scripts only, no reviewer agents) |"
             % render_reports.plugin_version(), "",
             "> **These are leads, not findings.** The quick scan matches patterns and reads manifests. It does not "
             "check whether input is user-controlled, whether a guard exists elsewhere, or whether the code is "
             "reachable. Expect false positives and missed issues. Run `/917v-code-review:review` to have the "
             "specialist agents confirm or reject each lead against the source.", "",
             "## At a glance", "",
             "| Measure | Value |", "|---|---:|",
             "| Files scanned | %d |" % files_scanned,
             "| Leads | %d |" % len(sigs),
             "| Areas with leads | %d |" % len(agents),
             "| Import cycles | %d |" % len(cycles), ""]

    lines += ["## Leads by area", ""]
    if agents:
        lines += ["| Area | Leads | Rules hit |", "|---|---:|---|"]
        for a in agents:
            rules = {}
            for s in by_agent[a]:
                rules[s["rule"]] = rules.get(s["rule"], 0) + 1
            lines.append("| %s | %d | %s |" % (area(a), len(by_agent[a]), cell(", ".join(
                "`%s` ×%d" % (r, n) if n > 1 else "`%s`" % r for r, n in sorted(rules.items(), key=lambda x: -x[1])))))
        if signals.get("truncated_rules"):
            lines += ["", "Some rules hit their per-rule cap and were truncated: %s." % ", ".join(
                "`%s`" % r for r in signals["truncated_rules"])]
    else:
        lines.append("_No pattern leads. That does not mean the code is clean: the scan only knows simple patterns._")
    lines.append("")

    for a in agents:
        items = by_agent[a]
        lines += ["### %s" % area(a), "", "| Location | Hint | Snippet |", "|---|---|---|"]
        for s in items[:MAX_LEADS_PER_AREA]:
            lines.append("| [`%s:%s`](../../%s#L%s) | %s | %s |" % (
                s["file"], s["line"], s["file"], s["line"], cell(s.get("hint")),
                code_span(cell((s.get("snippet") or "").strip()[:120]))))
        if len(items) > MAX_LEADS_PER_AREA:
            lines.append("| … | %d more in `.work/signals.json` | |" % (len(items) - MAX_LEADS_PER_AREA))
        lines.append("")

    lines += ["## Import cycles", ""]
    if imports is None:
        lines.append("_Not analysed in this scan._")
    elif cycles:
        lines += ["%d circular dependencies between internal files. Some are benign (for example ORM entities that "
                  "reference each other); the architecture review decides which are design problems." % len(cycles), ""]
        lines += ["- " + " → ".join("`%s`" % f for f in c.get("example_path") or c.get("files") or []) for c in cycles[:20]]
    else:
        lines.append("_No circular imports found._")
    lines.append("")

    lines += ["## Stack", "", render_reports.stack_summary(stack), ""]
    eps = [e["file"] for e in (stack or {}).get("entry_points") or []]
    crit = (stack or {}).get("critical_paths") or {}
    if eps or crit:
        lines += ["## Where a full review would start", ""]
        if eps:
            lines.append("- **Entry points:** " + ", ".join("`%s`" % e for e in eps[:10]))
        for k, v in crit.items():
            if v.get("count"):
                lines.append("- **%s** (%d): %s" % (k.replace("_", " ").capitalize(), v["count"], ", ".join(
                    "`%s`" % f for f in v.get("files", [])[:8]) + (" …" if v["count"] > 8 else "")))
        lines.append("")

    rec = [r["agent"] for r in (stack or {}).get("recommended_agents") or []]
    skipped = (stack or {}).get("skipped_agents") or []
    lines += ["## Next step", "",
              "Run `/917v-code-review:review` for validated findings with severities, evidence and fixes%s." % (
                  " (or `/917v-code-review:review-diff` with the same selector)" if scope else ""),
              "It would run: %s." % (", ".join("`%s`" % a for a in rec) or "the default agents")]
    if skipped:
        lines.append("It would skip: %s." % "; ".join("`%s` (%s)" % (s["agent"], s["reason"]) for s in skipped))
    text = "\n".join(lines).rstrip("\n") + "\n"

    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "scan.md"), "w", encoding="utf-8") as fh:
            fh.write(text)
    summary = {"repository": repo, "scope": scope_desc, "files_scanned": files_scanned, "leads": len(sigs),
               "leads_by_area": {area(a): len(by_agent[a]) for a in agents},
               "import_cycles": len(cycles) if imports is not None else None,
               "top_leads": [{"area": area(s["agent"]), "file": s["file"], "line": s["line"], "hint": s.get("hint")}
                             for a in agents for s in by_agent[a][:3]][:12],
               "recommended_agents": rec}
    return text, summary


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", required=True)
    ap.add_argument("--stack", required=True)
    ap.add_argument("--signals", required=True)
    ap.add_argument("--imports")
    ap.add_argument("--scope")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    check_output_path(a.root, a.out)
    if os.path.realpath(a.out) == os.path.realpath(os.path.join(a.root, OUTPUT_DIR)):
        claim_output_dir(a.root)
    opt = lambda p: load_json(p) if p and os.path.exists(p) else None
    _, summary = render(a.root, load_json(a.stack), load_json(a.signals), opt(a.imports), opt(a.scope), a.out)
    summary["written"] = os.path.join(a.out, "scan.md")
    dump_json(summary)


if __name__ == "__main__":
    main()
